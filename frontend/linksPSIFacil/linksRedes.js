/* =========================================================
   SEGURANÇA
========================================================= */

function escaparHtml(valor) {

    const elemento =
        document.createElement("div");


    elemento.textContent =
        String(valor || "");


    return elemento.innerHTML;

}


/* =========================================================
   CRIAR CARD
========================================================= */

function criarCardRede(rede, indice) {

    const icone =
        iconesRedes[rede.icone] || "";


    const classeCard =
        indice % 2 === 0
            ? "social-card-light"
            : "social-card-dark";


    return `

        <a
            href="${escaparHtml(rede.url)}"
            class="social-card ${classeCard}"
            target="_blank"
            rel="noopener noreferrer"
            aria-label="Abrir ${escaparHtml(rede.nome)} do PsiFácil"
        >

            <div class="social-icon">

                ${icone}

            </div>


            <div class="social-content">

                <strong>
                    ${escaparHtml(rede.nome)}
                </strong>


                <span>
                    ${escaparHtml(rede.descricao)}
                </span>

            </div>


            <div
                class="social-arrow"
                aria-hidden="true"
            >
                →
            </div>

        </a>

    `;

}


/* =========================================================
   RENDERIZAR
========================================================= */

function renderizarRedesSociais() {

    const container =
        document.getElementById(
            "socialLinks"
        );


    if (!container) {

        return;

    }


    container.innerHTML =
        redesSociais
            .map(criarCardRede)
            .join("");

}


/* =========================================================
   ANO
========================================================= */

function atualizarAno() {

    const elemento =
        document.getElementById(
            "anoAtual"
        );


    if (!elemento) {

        return;

    }


    elemento.textContent =
        new Date().getFullYear();

}


/* =========================================================
   LUCIDE
========================================================= */

function carregarIconesLucide() {

    if (!window.lucide) {

        return;

    }


    lucide.createIcons();

}


